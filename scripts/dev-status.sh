#!/bin/bash
# 开发步骤状态检查脚本
#
# 功能：
#     从总纲文档读取步骤列表，交叉验证步骤文件、提示词文件、发现文档，
#     汇总输出每步的当前状态和信号标记。
#
# 用途：
#     开发启动协议的第一步，在 read 步骤/发现文档之前获取全局视图。
#
# 依赖的文件（外部资源）：
#   docs/开发文档/P2开发文档/phase2b/00-总纲.md
#       — 总纲文件，包含"开发步骤"Markdown 表格，每行对应一个步骤
#   docs/开发文档/P2开发文档/phase2b/步骤/{文件名}.md
#       — 步骤文档，由总纲表格"步骤文件"列的 Markdown 链接指向
#   docs/开发文档/P2开发文档/phase2b/提示词/{编号}-*/
#       — 提示词目录，目录名以步骤编号开头，内含 .md 提示词文件
#   docs/开发文档/P2开发文档/phase2b/发现/{文件名}.md
#       — 发现文档，文件名与同步骤的步骤文档相同，内含"状态：⏳"行表示待确认项
#
# 依赖的命令：grep, sed, cut, tr, stat, date, find, wc, column
#
# 输出格式：
#   编号  文件                状态  距今    信号
#   ────  ──────────────────  ────  ──────  ────────
#   01    some-step          ✅     3天前
#   02    another-step       🔨    今天    📄⚠1🔥
#
# 信号列（可叠加）：
#   🔥 — 活跃：步骤文件最近 2 天内修改过，且有提示词文件存在
#   📄 — 有提示词：该步骤对应的提示词目录下存在 .md 文件
#   ⚠N — N 项待确认：发现文档中有 N 条状态为"⏳ 待确认"的条目
#   💀 — 脏/搁置：步骤状态为 🔨（进行中），但超过 2 天未修改
set -uo pipefail

# ── 配置 ──────────────────────────────────────────────────────────────────────
# 开发文档基础目录（相对于项目根目录）
D="docs/开发文档/P2开发文档/phase2b"
NOW=$(date +%s)  # 当前 Unix 时间戳，用于与文件修改时间比较

# ── 1. 从总纲提取步骤表格 ─────────────────────────────────────────────────────
#
# 总纲文件中的"开发步骤"表格结构：
#   ## 开发步骤
#   （空行）
#   | 编号 | 步骤文件 | 名称 | 状态 | ...（表头行）
#   |------|----------|------|------|------（分隔行）
#   | 01 | [文字](01-xxx.md) | ... | ✅ | ...（数据行）
#   | 02 | [文字](02-yyy.md) | ... | 🔨 | ...
#
# 提取流程：
#   1. 定位 "## 开发步骤" 标题的行号
#   2. 跳过 4 行（标题 + 空行 + 表头 + 分隔线）
#   3. 逐行读取，遇到空行或新标题则停止

start=$(grep -n '^## 开发步骤' "$D/00-总纲.md" | cut -d: -f1)
start=$((start + 4))
rows=$(sed -n "${start},\$p" "$D/00-总纲.md" | while IFS= read -r l; do
    # 只保留以 "| 数字" 开头的数据行（步骤行），遇到空行或新标题退出
    case "$l" in "| "[0-9]*) echo "$l" ;; ""|"#"*) break ;; esac
done)

# ── 2. 逐行解析步骤表格，生成状态输出 ──────────────────────────────────────────
#
# 总纲 Markdown 表格行格式（管道符分隔各列）：
#   | 编号 | [文字](步骤文件.md) | 名称 | 状态 |
#   f1    f2                    f3     f4    f5
#
# 列提取：
#   f2 → 步骤编号（如 "01"）
#   f3 → Markdown 链接 [文字](文件名.md)，从中提取文件名
#   f5 → 状态标记（如 ✅ / 🔨）
#
# 输出行用管道符分隔，传递给 column -t 对齐显示

output=""
while IFS= read -r row; do
    # 步骤编号（第 2 列）
    num=$(echo "$row" | cut -d'|' -f2 | tr -d ' ')

    # 步骤文档文件名（第 3 列为 Markdown 链接 [文字](文件名.md)）
    # sed 提取括号内路径：去掉 ".*(" 和 ")"
    file=$(echo "$row" | cut -d'|' -f3 | sed 's/.*(//;s/).*//')
    file_disp="${file%.md}"  # 显示时去掉 .md 后缀

    # 步骤状态（第 5 列）；为空时显示 "-"
    st=$(echo "$row" | cut -d'|' -f5 | tr -d ' ')
    [ -z "$st" ] && st="-"

    # 步骤文件路径，不存在则跳过该行
    sf="$D/步骤/$file"
    [ ! -f "$sf" ] && continue

    # ── 2a. 计算距今天数 ──────────────────────────────────────────────────────
    # stat -c %Y 返回文件最后修改时间的 Unix 时间戳
    # 若 stat 失败（文件被删除等），用当前时间兜底
    mt=$(stat -c %Y "$sf" 2>/dev/null || echo "$NOW")
    days=$(( (NOW - mt) / 86400 ))
    case $days in
        0) ds="今天" ;;
        1) ds="1天前" ;;
        *) ds="${days}天前" ;;
    esac

    # ── 2b. 统计提示词文件数量 ────────────────────────────────────────────────
    # 提示词目录以步骤编号开头，如 "01-xxx/"
    id=$(find "$D/提示词/" -maxdepth 1 -type d -name "${num}-*" 2>/dev/null | head -1)
    ic=0
    [ -n "$id" ] && ic=$(find "$id" -maxdepth 1 -name '*.md' 2>/dev/null | wc -l)

    # ── 2c. 统计发现文档中的待确认项 ──────────────────────────────────────────
    # 发现文档中每行 "状态：⏳" 代表一条待用户确认的事项
    df_disc="$D/发现/$file"
    pc=0
    [ -f "$df_disc" ] && pc=$(grep -c '状态：⏳' "$df_disc" 2>/dev/null) || pc=0

    # ── 2d. 组装信号列 ────────────────────────────────────────────────────────
    # 信号规则（可叠加）：
    #   📄 — 存在提示词文件（无论多少，只标记存在）
    #   ⚠N — 发现文档中有 N 条待确认项
    #   💀 — 状态为 "🔨"（进行中）但超过 2 天未修改，表示可能被搁置
    #   🔥 — 最近 2 天内有修改 + 存在提示词文件，表示有人正在推进
    sig=""
    [ "$ic" -gt 0 ]  && sig="📄 "                    # 有提示词
    [ "$pc" -gt 0 ]  && sig=" ${sig}⚠ ${pc}"         # 有待确认项
    [ "$st" = "🔨" ] && [ "$days" -gt 2 ] && sig=" ${sig} 💀 " # 脏/搁置
    [ "$days" -le 2 ] && [ "$ic" -gt 0 ] && sig=" ${sig} 🔥 "  # 活跃推进

    output+="${num}|${file_disp}     |${st}  |${ds}|${sig}"$'\n'
done <<< "$rows"

# ── 3. 输出主表格 ──────────────────────────────────────────────────────────────
# 表头+分隔行后，用 column -t 按列对齐显示
echo "编号  文件                状态  距今    信号"
echo "────  ──────────────────  ────  ──────  ────────"
echo -n "$output" | column -t -s '|' -o '  '

# ── 4. 检测总纲未列出的活跃步骤 ────────────────────────────────────────────────
#
# 场景：开发过程中可能新增了步骤文件但忘记同步总纲表格。
# 遍历步骤目录中所有 .md，跳过已在总纲 rows 中出现过的文件名，
# 只显示最近 2 天内有修改的"游离"步骤。
# 这类步骤的状态列标记为 "?"（来自总纲）。
extra_output=""
for sf in "$D"/步骤/*.md; do
    [ ! -f "$sf" ] && continue
    nm=$(basename "$sf" .md)
    echo "$rows" | grep -qF "$nm" && continue  # 总纲已涵盖则跳过

    # 只显示最近活跃的游离步骤
    mt=$(stat -c %Y "$sf" 2>/dev/null || echo "$NOW")
    days_x=$(( (NOW - mt) / 86400 ))
    [ "$days_x" -gt 2 ] && continue

    # 后续逻辑同主循环：统计提示词和待确认项
    nu=$(echo "$nm" | grep -oP '^\d+')
    id=$(find "$D/提示词/" -maxdepth 1 -type d -name "${nu}-*" 2>/dev/null | head -1)
    ic=0
    [ -n "$id" ] && ic=$(find "$id" -maxdepth 1 -name '*.md' 2>/dev/null | wc -l)
    df_disc="$D/发现/${nm}.md"
    pc=0
    [ -f "$df_disc" ] && pc=$(grep -c '状态：⏳' "$df_disc" 2>/dev/null) || pc=0

    # 游离步骤必带 🔥 标记（刚筛选过 days_x <= 2），如有待确认则叠加
    sig=""
    [ "$ic" -gt 0 ] && sig=" 📄 "
    [ "$pc" -gt 0 ] && sig="${sig} ⚠ ${pc} 🔥"
    extra_output+="${nu}|${nm}|?|今天|${sig}"$'\n'
done

if [ -n "$extra_output" ]; then
    echo ""
    echo "⚠ 以下步骤存在于步骤/目录但未被总纲表格涵盖："
    echo -n "$extra_output" | column -t -s '|' -o '  '
fi

# ── 5. 输出图例 ────────────────────────────────────────────────────────────────
echo ""
echo "🔥 = 活跃 📄 = 有提示词 ⚠ N = N 项待确认 💀 = 脏(🔨 但超 2 日未改)"
